import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import test from "node:test";
import ts from "typescript";
import zxing from "@zxing/library";

const source = await readFile(
  new URL("../src/lib/attendanceQr.ts", import.meta.url),
  "utf8",
);
const compiled = ts.transpileModule(source, {
  compilerOptions: { module: ts.ModuleKind.ESNext },
}).outputText;
const { parseAttendanceQr } = await import(
  `data:text/javascript;base64,${Buffer.from(compiled).toString("base64")}`
);

test("decodes a real matrix generated by the server's Python qrcode library", async () => {
  const fixture = JSON.parse(await readFile(new URL("./fixtures/attendance-qr.json", import.meta.url), "utf8"));
  const size = fixture.matrix.length * 4;
  const pixels = new Uint8ClampedArray(size * size);
  for (let y = 0; y < size; y++) for (let x = 0; x < size; x++)
    pixels[y * size + x] = fixture.matrix[Math.floor(y / 4)][Math.floor(x / 4)] === "1" ? 0 : 255;
  const bitmap = new zxing.BinaryBitmap(new zxing.HybridBinarizer(new zxing.RGBLuminanceSource(pixels, size, size)));
  const text = new zxing.QRCodeReader().decode(bitmap).getText();
  assert.equal(text, fixture.payload);
  assert.deepEqual(parseAttendanceQr(text), { sessionId: 12, token: "fixture-only-token" });
});

test("reads the generated attendance URL locally without navigating to its host", () => {
  assert.deepEqual(
    parseAttendanceQr(
      "http://192.168.1.100:8080/student/courses?attendance=12&token=abc_DEF-123",
    ),
    { sessionId: 12, token: "abc_DEF-123" },
  );
  assert.deepEqual(
    parseAttendanceQr("/student/courses?attendance=1&token=abc"),
    { sessionId: 1, token: "abc" },
  );
});

test("rejects unrelated, missing, ambiguous and unsafe QR payloads", () => {
  for (const text of [
    "hello",
    "https://example.com/",
    "/student/courses?attendance=-1&token=abc",
    "/student/courses?attendance=0&token=abc",
    "/student/courses?attendance=1.5&token=abc",
    "/student/courses?attendance=9007199254740999&token=abc",
    "/student/courses?attendance=1",
    "/student/courses?attendance=1&token=",
    "/student/courses?attendance=1&token=a%20b",
    "/student/courses?attendance=1&attendance=2&token=abc",
    "/student/courses?attendance=1&token=abc&token=xyz",
    "javascript:/student/courses?attendance=1&token=abc",
  ])
    assert.throws(() => parseAttendanceQr(text), Error, text);
});
